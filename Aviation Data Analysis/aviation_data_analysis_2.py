#Converting files to dataframes
df1 = pd.read_csv(r"C:\Users\deona\Downloads\Airport_Codes.csv")
df2 = pd.read_csv(r"C:\Users\deona\Downloads\Flights.csv", low_memory=False)
df3 = pd.read_csv(r"C:\Users\deona\Downloads\Tickets.csv")
df4 = pd.read_csv(r"C:\Users\deona\Downloads\airports.csv")
df1 = pd.DataFrame(df1)
flights = pd.DataFrame(df2)
tickets = pd.DataFrame(df3)
df4 = pd.DataFrame(df4)

#Renaming column to make merging process easier
df4.rename(columns={"iata":"IATA_CODE"},inplace = True)

#Merging airport files so dataframes contain needed data
airports = pd.merge(df1, df4, on="IATA_CODE")

#Merging dataframes on similiar columns
f1 = flights.merge(airports, left_on="ORIGIN", right_on="IATA_CODE", suffixes=("", "_ORIGIN"))

#Merging dataframes on similiar columns
flights = f1.merge(airports, left_on="DESTINATION", right_on="IATA_CODE",suffixes=("_ORIGIN", "_DEST"))

#Filtering dataframe so rows only include flights taken from medium and large airports
flights = flights[
    ((flights["TYPE_ORIGIN"] == "medium_airport") | (flights["TYPE_ORIGIN"] == "large_airport")) &
    ((flights["TYPE_DEST"] == "medium_airport") | (flights["TYPE_DEST"] == "large_airport"))
]

#Excluding flights that were cancelled
flights = flights[flights["CANCELLED"] == 0.0]

tickets["ITIN_FARE"] = pd.to_numeric(tickets["ITIN_FARE"], errors="coerce")

#Filtering dataframe so only roundtrips are included
roundtrip = tickets[tickets["ROUNDTRIP"] == 1.0]

#Only including roundtrip tickets for 1 passenger
roundtrip = roundtrip[roundtrip ["PASSENGERS"] == 1.0]

roundtrip1 = (roundtrip.groupby(["ORIGIN", "DESTINATION"])["ITIN_FARE"].mean().reset_index())

#Merging dataframes needed for analysis
flights_rt = pd.merge(
    flights,
    roundtrip1,
    on=["ORIGIN", "DESTINATION"])

flights_rt.head()

# Identifying the 10 busiest round-trip routes based on the number of round-trip flights in the quarter
tenbusiest = (
    flights_rt.groupby(["ORIGIN", "DESTINATION"])
      .size()
      .reset_index(name="Total Flights")
      .sort_values(by="Total Flights", ascending=False)
)

#Displaying the top 10 busiest flights
