#Creating a column to represent the baggage revenue for each flight
flights_rt["b_revenue"] = flights_rt["OCCUPANCY_RATE"]* 200 /2 * 70

#Changing name of existing column that represents flight price
flights_rt.rename(columns={"t_revenue":"Ticket_price"},inplace = True)

#Creating a column to represent the number passengers for each flight
flights_rt["Passengers"] = flights_rt["OCCUPANCY_RATE"]* 200

#Creating a column to represent the cost of Flight Ops for each flight
flights_rt["Flight_Ops"] = flights_rt["DISTANCE"]* 8

#Creating a column to represent the ticket revenue for each flight
flights_rt["t_revenue"] = flights_rt["Ticket_price"] * flights_rt["Passengers"]

#Creating a column to represent the profit made for each flight
flights_rt["Profit"] = (
    (flights_rt["t_revenue"] + flights_rt["b_revenue"])
    - (flights_rt["Flight_Ops"] + flights_rt["Overhead"] + flights_rt["Airportcost"])
)

