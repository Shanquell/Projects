def plot_calibration(expected_scores, predicted_scores):
    """
    Plot average expected credibility against average predicted
    credibility within score bins.
    """

    # Convert lists to NumPy arrays
    expected = np.asarray(expected_scores, dtype=float)
    predicted = np.asarray(predicted_scores, dtype=float)

    # Create five score bins:
    # 0.0-0.2, 0.2-0.4, 0.4-0.6, 0.6-0.8, 0.8-1.0
    bins = np.linspace(0.0, 1.0, 6)

    mean_predicted = []
    mean_expected = []

    # Calculate the average predicted and expected
    # score within each bin
    for lower, upper in zip(bins[:-1], bins[1:]):

        if upper == 1.0:
            mask = (predicted >= lower) & (predicted <= upper)
        else:
            mask = (predicted >= lower) & (predicted < upper)

        if np.any(mask):
            mean_predicted.append(predicted[mask].mean())
            mean_expected.append(expected[mask].mean())

    # Create the figure
    plt.figure(figsize=(7, 6))

    # Perfect calibration reference line
    plt.plot(
        [0, 1],
        [0, 1],
        linestyle="--",
        label="Perfect calibration"
    )

    # Actual credibility scorer calibration
    plt.plot(
        mean_predicted,
        mean_expected,
        marker="o",
        label="Credibility scorer"
    )

    # Labels and title
    plt.xlabel("Mean predicted score")
