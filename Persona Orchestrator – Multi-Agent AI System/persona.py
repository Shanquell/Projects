def validate_persona(spec: PersonaSpec) -> List[str]:
    """
    Validates a generated persona.

    Returns a list of validation errors.
    An empty list means the persona is valid.
    """
    errors = []

    if not spec.name.strip() or spec.name == "Unnamed":
        errors.append("Persona must have a name.")

    if not spec.role.strip() or spec.role == "unknown":
        errors.append("Persona must have a role.")

    if len(spec.role.split()) != 1:
        errors.append("Role must be one word.")

    required_sections = [
        "## Background",
        "## Personality",
        "## How they speak",
        "## What they want",
        "## What they avoid",
    ]

    for section in required_sections:
        if section.lower() not in spec.body.lower():
            errors.append(f"Missing required section: {section}")

    return errors

def generate_persona(description: str, llm: LLM) -> PersonaSpec:
    """
    Ask the model to author a persona from a one-line description.

    The model may occasionally ignore the requested markdown format.
    Generation should still return a usable PersonaSpec rather than
    crashing the application.
    """

    markdown = llm.complete(
        system=_AUTHOR_SYSTEM,
        messages=[
            {
                "role": "user",
                "content": f"Write a persona for: {description}",
            }
        ],
        max_tokens=2048,
    )

    spec = PersonaSpec.from_markdown(markdown)

    # -------------------------------------------------------------
    # Fallback name
    # -------------------------------------------------------------
    if not spec.name or spec.name == "Unnamed":
        spec.name = description[:40].strip().title() or "Unnamed"

    # -------------------------------------------------------------
    # Fallback role
    # -------------------------------------------------------------
    if not spec.role or spec.role == "unknown":
        words = description.strip().split()

        if words:
            # Remove a leading article when possible.
            if words[0].lower() in {"a", "an", "the"} and len(words) > 1:
                spec.role = words[1].lower()
            else:
                spec.role = words[0].lower()
        else:
            spec.role = "person"

    # -------------------------------------------------------------
    # Fallback summary
    # -------------------------------------------------------------
    if not spec.summary:
        spec.summary = description.strip()

    # -------------------------------------------------------------
    # Preserve whatever body the model returned.
    # -------------------------------------------------------------
    if not spec.body.strip():
        spec.body = markdown.strip() or description.strip()

    return spec