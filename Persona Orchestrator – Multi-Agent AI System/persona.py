def save_persona(
    spec: PersonaSpec,
    directory: Path = DEFAULT_PERSONA_DIR,
) -> Path:
    """
    Save a persona without overwriting an existing persona.

    Duplicate files receive a numeric suffix:
    maria-delgado.md
    maria-delgado-2.md
    maria-delgado-3.md
    """
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)

    base_slug = spec.slug()
    path = directory / f"{base_slug}.md"

    counter = 2

    while path.exists():
        path = directory / f"{base_slug}-{counter}.md"
        counter += 1

    path.write_text(
        spec.to_markdown(),
        encoding="utf-8",
    )

    return path


def load_persona(path: Path) -> PersonaSpec:
    """Read one persona file from disk."""
    return PersonaSpec.from_markdown(
        Path(path).read_text(encoding="utf-8")
    )


def list_personas(
    directory: Path = DEFAULT_PERSONA_DIR,
) -> List[PersonaSpec]:
    """
    Return every persona currently saved,
    sorted by filename. Empty if none exist.
    """
    directory = Path(directory)

    if not directory.exists():
        return []

    return [
        load_persona(path)
        for path in sorted(directory.glob("*.md"))
    ]


