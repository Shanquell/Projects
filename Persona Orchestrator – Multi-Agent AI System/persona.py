def find_persona(
    name: str,
    directory: Path = DEFAULT_PERSONA_DIR,
) -> Optional[PersonaSpec]:
    """
    Find a persona by exact name, slug, role,
    or unique partial name.

    Matching priority:
    1. Exact name
    2. Exact slug
    3. Exact role, only if one persona has that role
    4. Partial name, only if exactly one persona matches

    Ambiguous matches return None.
    """
    needle = name.strip().lower()
    personas = list_personas(directory)

    if not needle:
        return None

    # 1. Exact name
    exact_name = [
        spec
        for spec in personas
        if spec.name.lower() == needle
    ]

    if len(exact_name) == 1:
        return exact_name[0]

    # 2. Exact slug
    exact_slug = [
        spec
        for spec in personas
        if spec.slug() == needle
    ]

    if len(exact_slug) == 1:
        return exact_slug[0]

    # 3. Exact role
    role_matches = [
        spec
        for spec in personas
        if spec.role.lower() == needle
    ]

    if len(role_matches) == 1:
        return role_matches[0]

    if len(role_matches) > 1:
        return None

    # 4. Partial name
    partial_matches = [
        spec
        for spec in personas
        if needle in spec.name.lower()
    ]

    if len(partial_matches) == 1:
        return partial_matches[0]

    return None
