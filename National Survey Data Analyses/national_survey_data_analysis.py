def pie_chart(series, title):
    counts = series.dropna().value_counts()

    plt.figure(figsize=(7, 7))

    plt.pie(
        counts.values,
        labels=counts.index,
        autopct="%1.1f%%",
        startangle=90
    )

    plt.title(title)
    plt.tight_layout()
    plt.show()


def bar_chart(series, title, xlabel, ylabel):
    counts = series.dropna().value_counts()

    plt.figure(figsize=(8, 5))

    bars = plt.bar(
        counts.index.astype(str),
        counts.values
    )

    # SAS-like datalabel
    for bar in bars:
        height = bar.get_height()

        plt.text(
            bar.get_x() + bar.get_width() / 2,
            height,
            f"{int(height)}",
            ha="center",
            va="bottom"
        )

    plt.xlabel(xlabel)
    plt.ylabel(ylabel)
    plt.title(title)
    plt.tight_layout()
    plt.show()


