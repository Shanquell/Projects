#
# These are similar to SAS PROC FORMAT.
# Original numeric variables are preserved.
# ============================================================

prac2["Smoke_Frequency"] = prac2["SMQ040"].map(smq_labels)

prac2["Physical_Activity_Status"] = prac2["LPA"].map(pa_labels)

