import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from pathlib import Path


# ============================================================
# 1. SET DATA DIRECTORY
# SAS equivalent:
# libname NHANES '/home/u61677009/Data Analysis Project';
# ============================================================

DATA_DIR = Path("/home/u61677009/Data Analysis Project")


# ============================================================
# 2. IMPORT NHANES XPT FILES
# SAS equivalent:
# libname DPQ XPORT ".../DPQ_I.XPT";
# ============================================================

dpq = pd.read_sas(DATA_DIR / "DPQ_I.XPT", format="xport")
paq = pd.read_sas(DATA_DIR / "PAQ_I.XPT", format="xport")

# Your SAS filename contains a space before ".XPT".
# Change this filename if the actual file is named SMQ_I.XPT.
smq_file = DATA_DIR / "SMQ_I .XPT"

if not smq_file.exists():
    smq_file = DATA_DIR / "SMQ_I.XPT"

smq = pd.read_sas(smq_file, format="xport")
demo = pd.read_sas(DATA_DIR / "DEMO_I.XPT", format="xport")


# ============================================================
# 3. SORT DATASETS BY SEQN
# SAS equivalent:
# proc sort data=...;
# by SEQN;
# ============================================================

dpq = dpq.sort_values("SEQN")
paq = paq.sort_values("SEQN")
smq = smq.sort_values("SEQN")
demo = demo.sort_values("SEQN")


# ============================================================
# 4. MERGE ALL DATASETS
#
# SAS:
# merge dpq_i(in=a)
#       paq_i(in=b)
#       smq_i(in=c)
#       demo_i(in=d);
# by SEQN;
# if a and b and c and d;
#
# inner merge keeps participants present in all four datasets.
# ============================================================

projprac = (
    dpq
    .merge(paq, on="SEQN", how="inner")
    .merge(smq, on="SEQN", how="inner")
    .merge(demo, on="SEQN", how="inner")
)

print("\nMerged dataset dimensions:")
print(projprac.shape)

print("\nFirst five observations:")
print(projprac.head())


# ============================================================
# 5. FREQUENCY TABLE FOR DPQ020
# SAS equivalent:
# proc freq data=projprac;
# tables DPQ020;
# ============================================================

print("\nDPQ020 Frequency Table:")
print(
    projprac["DPQ020"]
    .value_counts(dropna=False)
    .sort_index()
)

print("\nMissing DPQ020 values:")
print(projprac["DPQ020"].isna().sum())


# ============================================================
# 6. CREATE PRAC1
# ============================================================

prac1 = projprac.copy()


# ------------------------------------------------------------
# Clean SMD650
#
# SAS:
# if smd650=. or smd650=999 or smd650=95
# then smd650=.;
# ------------------------------------------------------------

prac1["SMD650"] = prac1["SMD650"].replace(
    [999, 95],
    np.nan
)


# ------------------------------------------------------------
# Create SMOKE variable
#
# SAS:
# if SMQ040=. then SMQ040=.;
# else if SMQ040<=2 then SMOKE=1;
# else SMOKE=2;
#
# 1 = Smoke
# 2 = Don't Smoke
# ------------------------------------------------------------

prac1["SMOKE"] = np.select(
    [
        prac1["SMQ040"].isin([1, 2]),
        prac1["SMQ040"] > 2
    ],
    [
        1,
        2
    ],
    default=np.nan
)


# ------------------------------------------------------------
# Clean PAQ670 and create LPA
#
# SAS:
# if PAQ670=99 or PAQ670=. then PAQ670=.;
# else if PAQ670<3 then LPA=1;
# else LPA=2;
#
# 1 = Low
# 2 = Normal
# ------------------------------------------------------------

prac1["PAQ670"] = prac1["PAQ670"].replace(
    99,
    np.nan
)

prac1["LPA"] = np.select(
    [
        prac1["PAQ670"] < 3,
        prac1["PAQ670"] >= 3
    ],
    [
        1,
        2
    ],
    default=np.nan
)


