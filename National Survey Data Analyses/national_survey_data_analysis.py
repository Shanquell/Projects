# ============================================================
# 10. CREATE PRAC2
#
# SAS:
# keep=RIDAGEYR SMD650 PAQ670 SMQ040
#      LPA SMOKE DPQ020 RIAGENDR
#
# if 18<=RIDAGEYR<=30 and RIAGENDR=1;
# if 1<=DPQ020<=3;
# ============================================================

